-- Desempenho individual do estudante. Schema compatível com o banco existente.
CREATE TABLE IF NOT EXISTS public.question_attempts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  question_id integer NOT NULL REFERENCES public.questions(id) ON DELETE CASCADE,
  selected_letter varchar(1) NOT NULL,
  is_correct boolean NOT NULL DEFAULT false,
  seconds_spent integer CHECK (seconds_spent IS NULL OR seconds_spent >= 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_question_attempts_user ON public.question_attempts(user_id);
CREATE INDEX IF NOT EXISTS idx_question_attempts_question ON public.question_attempts(question_id);
CREATE INDEX IF NOT EXISTS idx_question_attempts_created ON public.question_attempts(created_at DESC);

CREATE TABLE IF NOT EXISTS public.student_topic_performance (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  topic_id integer NOT NULL REFERENCES public.topics(id) ON DELETE CASCADE,
  attempt_count integer NOT NULL DEFAULT 0,
  correct_count integer NOT NULL DEFAULT 0,
  accuracy numeric(6,5) NOT NULL DEFAULT 0,
  last_attempt_at timestamptz,
  UNIQUE(user_id, topic_id)
);

CREATE INDEX IF NOT EXISTS idx_student_topic_performance_user ON public.student_topic_performance(user_id);
CREATE INDEX IF NOT EXISTS idx_student_topic_performance_topic ON public.student_topic_performance(topic_id);

ALTER TABLE public.question_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.student_topic_performance ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS attempts_self ON public.question_attempts;
CREATE POLICY attempts_self ON public.question_attempts FOR ALL TO authenticated USING (user_id = auth.uid()) WITH CHECK (user_id = auth.uid());

DROP POLICY IF EXISTS performance_self ON public.student_topic_performance;
CREATE POLICY performance_self ON public.student_topic_performance FOR ALL TO authenticated USING (user_id = auth.uid()) WITH CHECK (user_id = auth.uid());
