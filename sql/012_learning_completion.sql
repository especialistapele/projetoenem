-- Completa o ciclo de aprendizagem: proficiência, prioridades, metas e agenda dos simulados.
CREATE TABLE IF NOT EXISTS public.proficiency_assessment_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assessment_id bigint NOT NULL REFERENCES public.proficiency_assessments(id) ON DELETE CASCADE,
  question_id integer NOT NULL REFERENCES public.questions(id) ON DELETE CASCADE,
  position integer NOT NULL,
  selected_letter varchar(1),
  is_correct boolean,
  answered_at timestamptz,
  UNIQUE(assessment_id, question_id), UNIQUE(assessment_id, position)
);
CREATE INDEX IF NOT EXISTS idx_prof_items_assessment ON public.proficiency_assessment_items(assessment_id, position);
ALTER TABLE public.proficiency_assessment_items ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS proficiency_items_own ON public.proficiency_assessment_items;
CREATE POLICY proficiency_items_own ON public.proficiency_assessment_items FOR ALL TO authenticated
USING (assessment_id IN (SELECT id FROM public.proficiency_assessments WHERE user_id=auth.uid()) OR public.is_admin())
WITH CHECK (assessment_id IN (SELECT id FROM public.proficiency_assessments WHERE user_id=auth.uid()) OR public.is_admin());

-- Metadados de agenda para os três ciclos anuais.
ALTER TABLE public.simulations ADD COLUMN IF NOT EXISTS cycle_month integer;
ALTER TABLE public.simulations ADD COLUMN IF NOT EXISTS description text;

-- Curso objetivo do aluno já usa user_profiles.program_id; garante índice.
CREATE INDEX IF NOT EXISTS idx_user_profiles_program ON public.user_profiles(program_id);
