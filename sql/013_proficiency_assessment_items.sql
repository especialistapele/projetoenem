-- Fase final — itens do teste de proficiência
-- Deve ser aplicada após 012_learning_completion.sql.

create table if not exists public.proficiency_assessment_items (
  id bigint generated by default as identity primary key,
  assessment_id bigint not null references public.proficiency_assessments(id) on delete cascade,
  question_id integer not null references public.questions(id) on delete restrict,
  position integer not null,
  selected_letter varchar null,
  is_correct boolean null,
  answered_at timestamptz null
);

create unique index if not exists proficiency_assessment_items_assessment_position_uidx
  on public.proficiency_assessment_items (assessment_id, position);

create unique index if not exists proficiency_assessment_items_assessment_question_uidx
  on public.proficiency_assessment_items (assessment_id, question_id);

create index if not exists proficiency_assessment_items_question_idx
  on public.proficiency_assessment_items (question_id);

alter table public.proficiency_assessment_items enable row level security;

-- O aluno só pode consultar/inserir/atualizar os itens de suas próprias avaliações.
create policy proficiency_assessment_items_student_select
  on public.proficiency_assessment_items
  for select
  to authenticated
  using (
    exists (
      select 1
      from public.proficiency_assessments a
      where a.id = proficiency_assessment_items.assessment_id
        and a.user_id = auth.uid()
    )
  );

create policy proficiency_assessment_items_student_insert
  on public.proficiency_assessment_items
  for insert
  to authenticated
  with check (
    exists (
      select 1
      from public.proficiency_assessments a
      where a.id = proficiency_assessment_items.assessment_id
        and a.user_id = auth.uid()
    )
  );

create policy proficiency_assessment_items_student_update
  on public.proficiency_assessment_items
  for update
  to authenticated
  using (
    exists (
      select 1
      from public.proficiency_assessments a
      where a.id = proficiency_assessment_items.assessment_id
        and a.user_id = auth.uid()
    )
  )
  with check (
    exists (
      select 1
      from public.proficiency_assessments a
      where a.id = proficiency_assessment_items.assessment_id
        and a.user_id = auth.uid()
    )
  );

-- Administradores precisam consultar os itens para suporte/auditoria.
create policy proficiency_assessment_items_admin_select
  on public.proficiency_assessment_items
  for select
  to authenticated
  using (
    exists (
      select 1 from public.user_profiles p
      where p.user_id = auth.uid() and p.role = 'admin'
    )
  );
