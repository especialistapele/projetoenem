CREATE TABLE IF NOT EXISTS public.simulations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_year integer NOT NULL,
  sequence integer NOT NULL CHECK (sequence BETWEEN 1 AND 3),
  title text NOT NULL,
  scheduled_at timestamptz,
  question_count integer NOT NULL DEFAULT 180,
  status text NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled','ready','open','closed')),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(cycle_year, sequence)
);
CREATE TABLE IF NOT EXISTS public.simulation_attempts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  simulation_id bigint NOT NULL REFERENCES public.simulations(id) ON DELETE CASCADE,
  question_id integer NOT NULL REFERENCES public.questions(id) ON DELETE CASCADE,
  position integer NOT NULL,
  user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE,
  selected_letter text,
  is_correct boolean,
  seconds_spent integer,
  answered_at timestamptz,
  UNIQUE(simulation_id, position),
  UNIQUE(simulation_id, user_id, question_id)
);
CREATE TABLE IF NOT EXISTS public.essay_submissions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  title text NOT NULL,
  content_text text NOT NULL,
  submitted_at timestamptz NOT NULL DEFAULT now(),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','reviewed'))
);
CREATE TABLE IF NOT EXISTS public.essay_reviews (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  essay_id bigint NOT NULL UNIQUE REFERENCES public.essay_submissions(id) ON DELETE CASCADE,
  reviewer_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  score numeric(6,2) NOT NULL DEFAULT 0,
  competency_1 numeric(6,2) NOT NULL DEFAULT 0,
  competency_2 numeric(6,2) NOT NULL DEFAULT 0,
  competency_3 numeric(6,2) NOT NULL DEFAULT 0,
  competency_4 numeric(6,2) NOT NULL DEFAULT 0,
  competency_5 numeric(6,2) NOT NULL DEFAULT 0,
  strengths text,
  improvements text,
  feedback text,
  reviewed_at timestamptz
);
CREATE INDEX IF NOT EXISTS idx_simulation_attempts_user ON public.simulation_attempts(user_id);
CREATE INDEX IF NOT EXISTS idx_essays_user ON public.essay_submissions(user_id, submitted_at DESC);
CREATE INDEX IF NOT EXISTS idx_essays_status ON public.essay_submissions(status);
ALTER TABLE public.simulations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.simulation_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.essay_submissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.essay_reviews ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS simulations_read_auth ON public.simulations;
CREATE POLICY simulations_read_auth ON public.simulations FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS simulation_attempts_own ON public.simulation_attempts;
CREATE POLICY simulation_attempts_own ON public.simulation_attempts FOR ALL TO authenticated USING (user_id = auth.uid() OR user_id IS NULL) WITH CHECK (user_id = auth.uid() OR user_id IS NULL);
DROP POLICY IF EXISTS essays_own ON public.essay_submissions;
CREATE POLICY essays_own ON public.essay_submissions FOR ALL TO authenticated USING (user_id = auth.uid()) WITH CHECK (user_id = auth.uid());
DROP POLICY IF EXISTS reviews_read_own ON public.essay_reviews;
CREATE POLICY reviews_read_own ON public.essay_reviews FOR SELECT TO authenticated USING (EXISTS (SELECT 1 FROM public.essay_submissions e WHERE e.id = essay_id AND e.user_id = auth.uid()) OR reviewer_id = auth.uid());
DROP POLICY IF EXISTS reviews_teacher_write ON public.essay_reviews;
CREATE POLICY reviews_teacher_write ON public.essay_reviews FOR ALL TO authenticated USING ((SELECT public.is_admin()) OR reviewer_id = auth.uid()) WITH CHECK ((SELECT public.is_admin()) OR reviewer_id = auth.uid());
