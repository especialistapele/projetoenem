CREATE TABLE IF NOT EXISTS public.question_classification_candidates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question_id bigint NOT NULL REFERENCES public.questions(id) ON DELETE CASCADE,
  area text,
  discipline text,
  competency text,
  skill text,
  topic_id bigint REFERENCES public.topics(id) ON DELETE SET NULL,
  confidence numeric(5,4) NOT NULL DEFAULT 0,
  classifier_version text NOT NULL DEFAULT 'heuristic-v1',
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','rejected','review')),
  evidence jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  reviewed_at timestamptz,
  reviewed_by uuid REFERENCES auth.users(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_qcc_question ON public.question_classification_candidates(question_id);
CREATE INDEX IF NOT EXISTS idx_qcc_status ON public.question_classification_candidates(status);
CREATE INDEX IF NOT EXISTS idx_qcc_confidence ON public.question_classification_candidates(confidence DESC);
ALTER TABLE public.question_classification_candidates ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS qcc_authenticated_read ON public.question_classification_candidates;
CREATE POLICY qcc_authenticated_read ON public.question_classification_candidates FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS qcc_admin_write ON public.question_classification_candidates;
CREATE POLICY qcc_admin_write ON public.question_classification_candidates FOR ALL TO authenticated USING ((SELECT public.is_admin())) WITH CHECK ((SELECT public.is_admin()));
CREATE OR REPLACE VIEW public.question_classification_metrics AS
SELECT count(*) AS total_candidates,
 count(*) FILTER (WHERE status='pending') AS pending,
 count(*) FILTER (WHERE status='review') AS review,
 count(*) FILTER (WHERE status='accepted') AS accepted,
 count(*) FILTER (WHERE status='rejected') AS rejected,
 round(avg(confidence),4) AS average_confidence,
 count(*) FILTER (WHERE confidence>=0.85) AS high_confidence,
 count(*) FILTER (WHERE confidence<0.60) AS low_confidence
FROM public.question_classification_candidates;
